#!/usr/bin/env python3
"""Generate the native English translation table from the Version 2.0 i18n.js."""

import json
import re
import sys
from pathlib import Path


def decode_js_string(value):
    escapes = {
        "'": "'",
        '"': '"',
        "\\": "\\",
        "/": "/",
        "n": "\n",
        "r": "\r",
        "t": "\t",
        "b": "\b",
        "f": "\f",
    }

    def replace(match):
        token = match.group(1)
        if token.startswith("u"):
            return chr(int(token[1:], 16))
        if token.startswith("x"):
            return chr(int(token[1:], 16))
        return escapes.get(token, token)

    return re.sub(r"\\(u[0-9a-fA-F]{4}|x[0-9a-fA-F]{2}|.)", replace, value)


def cpp_string(value):
    result = ['"']
    for char in value:
        code = ord(char)
        if char == "\\":
            result.append("\\\\")
        elif char == '"':
            result.append('\\"')
        elif char == "\n":
            result.append("\\n")
        elif char == "\r":
            result.append("\\r")
        elif char == "\t":
            result.append("\\t")
        elif char == "\b":
            result.append("\\b")
        elif char == "\f":
            result.append("\\f")
        elif code < 32 or code == 127:
            result.append("\\%03o" % code)
        else:
            result.append(char)
    result.append('"')
    return "".join(result)


def main():
    if len(sys.argv) != 2:
        raise SystemExit(
            "Usage: python3 tools/gen_strings.py ../s650-interface-concept/js/i18n.js"
        )

    source = Path(sys.argv[1]).read_text(encoding="utf-8")
    try:
        body = source.split("var en = {", 1)[1].split("var fr = {", 1)[0]
    except IndexError:
        raise SystemExit("Could not locate the English translation object")

    raw_pairs = re.findall(
        r"'((?:[^'\\]|\\.)*)'\s*:\s*'((?:[^'\\]|\\.)*)'",
        body,
    )
    pairs = [(decode_js_string(k), decode_js_string(v)) for k, v in raw_pairs]

    if not pairs:
        raise SystemExit("No English translations were found")

    keys = [key for key, _ in pairs]
    if len(keys) != len(set(keys)):
        raise SystemExit("Duplicate English translation keys found")

    print(
        "// GENERATED by tools/gen_strings.py from the Version 2.0 "
        "i18n.js (English table). Do not edit by hand."
    )
    print('#include "core/Translation.h"')
    print()
    print("namespace s650 {")
    print()
    print("const TranslationEntry kEnglish[] = {")

    for key, value in pairs:
        print("    {%s, %s}," % (cpp_string(key), cpp_string(value)))

    print("};")
    print()
    print("const size_t kEnglishCount = sizeof(kEnglish) / sizeof(kEnglish[0]);")
    print()
    print("} // namespace s650")


if __name__ == "__main__":
    main()
